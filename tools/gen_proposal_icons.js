// Regenerates proposal-assets.js (icon PNGs used in the Proposal .pptx).
// Run from the repo root on a machine with react, react-dom, react-icons and sharp installed:
//   node tools/gen_proposal_icons.js
const fs = require('fs'), path = require('path');
const React = require('react'), RDS = require('react-dom/server'), sharp = require('sharp');
const fa = require('react-icons/fa'), tb = require('react-icons/tb'), gi = require('react-icons/gi');
const C = { navy: '0A2350', orange: 'F0661A', green: '11905A', sun: 'FFB01F', grey: '7783A0', red: 'C42F2A', W: 'FFFFFF', cam: 'A9B3C7' };
const LIST = {
  cam: [fa.FaCamera, C.cam], sun: [fa.FaSun, C.sun], moon: [fa.FaMoon, C.navy],
  panel: [fa.FaSolarPanel, C.orange], panelW: [fa.FaSolarPanel, C.W], inv: [tb.TbDeviceAnalytics, C.navy], invW: [tb.TbDeviceAnalytics, C.W],
  home: [fa.FaHome, C.green], grid: [gi.GiElectric, C.grey], gridRed: [gi.GiElectric, C.red], batt: [tb.TbBatteryCharging2, C.green], battW: [tb.TbBatteryCharging2, C.W],
  check: [fa.FaCheck, C.W], cross: [fa.FaTimes, C.W], tools: [fa.FaTools, C.W], sign: [fa.FaFileSignature, C.W],
  step1: [fa.FaSearchLocation, C.W], step2: [fa.FaDraftingCompass, C.W], step3: [fa.FaHandshake, C.W], step4: [fa.FaHardHat, C.W], step5: [fa.FaClipboardCheck, C.W]
};
(async () => {
  const out = {};
  for (const [k, [Comp, col]] of Object.entries(LIST)) {
    const svg = RDS.renderToStaticMarkup(React.createElement(Comp, { color: '#' + col, size: '192' }));
    out[k] = 'image/png;base64,' + (await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toBuffer()).toString('base64');
  }
  const js = '/* generated by tools/gen_proposal_icons.js — icons for the Proposal .pptx */\n(typeof window!=="undefined"?window:globalThis).ST_PROPOSAL_ICONS=' + JSON.stringify(out) + ';\n';
  fs.writeFileSync(path.join(__dirname, '..', 'proposal-assets.js'), js);
  console.log('proposal-assets.js', Math.round(js.length / 1024), 'KB');
})();
